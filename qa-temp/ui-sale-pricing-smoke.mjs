import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { loadJSDOM } from '../test-support/jsdom.mjs';
import { INITIAL_ACCOUNTS } from '../domain.mjs';
import { Repository } from '../repository.mjs';

test('cash sale stores optional line pricing, restores the draft, and protects customer receipts', async t => {
  const JSDOM=await loadJSDOM();
  const repo=new Repository(':memory:','demo');
  const balances=Object.fromEntries(INITIAL_ACCOUNTS.filter(a=>!a.retired).map(a=>[a.id,'0']));
  balances.ceyrek='4';
  repo.execute({id:'open',revision:0,command:{type:'opening',date:'2026-11-10',balances}});
  const dom=new JSDOM(readFileSync(new URL('../public/index.html',import.meta.url),'utf8'),{url:'http://127.0.0.1:4317/',runScripts:'outside-only'});
  const {window}=dom, {document}=window;
  const get=s=>document.querySelector(s),tick=()=>new Promise(resolve=>setTimeout(resolve,0));
  t.after(()=>{window.close();repo.close();});
  Object.defineProperty(window.crypto,'randomUUID',{value:randomUUID});
  window.fetch=async(url,opts={})=>{
    const u=new URL(url,window.location.href);
    let body;
    if(u.pathname==='/api/state')body=repo.state();
    else if(u.pathname==='/api/command')body=repo.execute(JSON.parse(opts.body));
    else if(u.pathname==='/api/journal')body=repo.journalPage(Object.fromEntries(u.searchParams));
    else throw Error('Unexpected test route '+u.pathname);
    return {ok:true,json:async()=>body};
  };
  const script=readFileSync(new URL('../public/app.js',import.meta.url),'utf8');
  window.eval(script+'\nwindow.__receipt=statementReceipt;');
  await tick();get('[data-view="transaction"]').click();
  const write=(el,value)=>{assert.ok(el);el.value=value;el.dispatchEvent(new window.Event(el.tagName==='SELECT'?'change':'input',{bubbles:true}));};
  const p=key=>get('[data-price-field="'+key+'"]');
  assert.ok(p('costTL'),'retail price editor must distinguish unknown and explicit cost');
  assert.equal(p('costTL').required,false);
  write(p('costTL'),'999');
  write(get('[data-item-field="accountId"]'),'ceyrek');
  assert.equal(p('costTL').value,'','previous stock card cost must not transfer to another product');
  write(get('[data-item-field="accountId"]'),'ceyrek');write(get('[data-item-field="value"]'),'100');
  write(p('quotedTL'),'125');write(p('source'),'Etiket <x>');write(p('costTL'),'87.43');
  get('[data-add-price-component]').click();
  write(p('label'),'İndirim');write(p('amountTL'),'-2.50');
  get('[data-tab="purchase"]').click();assert.equal(p('costTL'),null);
  get('[data-tab="sale"]').click();
  assert.equal(p('amountTL').value,'-2.50');assert.equal(p('costTL').value,'87.43');
  get('[data-add-allocation="payment"][data-payment-type="cash"]').click();
  write(get('[data-allocation-kind="payment"] [data-allocation-field="quantity"]'),'100');
  get('#sale-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  await tick();
  const record=repo.state().journal.at(-1);
  assert.equal(record.type,'sale');
  assert.equal(record.meta.lines[0].pricing.costTL,8743);
  get('[data-view="journal"]').click();await tick();
  const privateDetail=get('[data-private-sale-pricing]');
  assert.match(privateDetail.textContent,/87,43 TL/);
  assert.match(privateDetail.textContent,/125,00 TL/);
  assert.match(privateDetail.textContent,/100,00 TL/);
  assert.match(privateDetail.textContent,/−2,50 TL|-2,50 TL/);
  assert.match(privateDetail.textContent,/Etiket <x>/);
  assert.equal(privateDetail.querySelector('x'),null);
  assert.doesNotMatch(window.__receipt(record,[record]),/87,43|87\.43|8743|maliyet/i);
  get('[data-edit-transaction]').click();
  assert.equal(p('quotedTL').value,'125');
  assert.equal(p('costTL').value,'87.43');
  assert.equal(p('label').value,'İndirim');
});
